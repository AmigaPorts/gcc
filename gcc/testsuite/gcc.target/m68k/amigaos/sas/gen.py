#!/usr/bin/env python3
"""Generate the SAS/C interoperability tests for -mmangle-regparm.

Each group of functions is written three times: G-callee.c defines them,
G-caller.c calls each one and stores what it returned, G-driver.c (gcc
only) runs G-caller.c's run_G() and compares the results with the values
computed here.  The callee and caller halves are plain C that both gcc
and SAS/C compile, so a program can be linked from any pairing of them.

Every function mixes its arguments into a 32-bit value in order, with
rotates and xors only (no multiply: SAS/C would call sc.lib for it on a
68000), so a swapped, dropped or misread argument changes the result.

Run it in this directory: ./gen.py.  sas.sh then compiles the SAS/C
halves; the objects it makes are checked in, since SAS/C cannot run in
CI.
"""

import itertools

SEED = 0x5A5A0000
M32 = 0xFFFFFFFF


def mix(h, v):
    h = ((h << 5) | (h >> 27)) & M32
    return h ^ (v & M32)


def s32(v):
    v &= M32
    return v - (1 << 32) if v & 0x80000000 else v


# Argument types: letter -> (C type, how the callee turns it into a long)
TYPES = {
    "l": ("long", "{a}"),
    "p": ("long *", "*{a}"),
    "c": ("signed char", "(long){a}"),
    "s": ("short", "(long){a}"),
    "S": ("struct s8", "{a}.x ^ {a}.y"),
    "T": ("struct s4", "{a}.x"),
    "d": ("double", "(long)({a} * 4.0)"),
}


def arg_value(t, k):
    """The value passed as argument k of type t, as the callee sees it
    after TYPES' conversion: a Python int, or for S a pair."""
    if t in "lp":
        return 0x01020304 * (k + 1) ^ (0x10000000 << (k % 3)) | (k << 28)
    if t == "c":
        return [-5, 100, -128, 7, -1, 33][k % 6]
    if t == "s":
        return [-1234, 30000, -32768, 9, -2, 4321][k % 6]
    if t == "S":
        return (0x11110000 + k, -0x2222 - k)
    if t == "T":
        return 0x7E000000 - k
    if t == "d":
        return [1.5, -2.25, 1000.75, -0.5, 3.0, -7.25][k % 6]
    raise ValueError(t)


def c_literal(t, v):
    if t == "d":
        return repr(v)
    if t == "S":
        return "{ %dL, %dL }" % v
    return "%dL" % s32(v)


def as_long(t, v):
    if t == "S":
        return v[0] ^ v[1]
    if t == "d":
        return int(v * 4.0)
    return v


class Fn:
    """One function: its argument types, its return type and, for the
    asm group, the register of each argument."""

    def __init__(self, args, ret="l", regs=None):
        self.args = args
        self.ret = ret
        self.regs = regs
        sig = args or "v"
        if regs:
            sig = "_".join(regs)
        self.name = "%s_%s" % ({"l": "f", "c": "rc", "s": "rs", "p": "rp",
                                 "S": "rS", "d": "rd"}[ret], sig)

    def expected(self, index):
        h = SEED + index
        for k, t in enumerate(self.args):
            h = mix(h, as_long(t, arg_value(t, k)))
        if self.ret == "c":
            h = s32((h & 0xFF) - 0x100 if h & 0x80 else h & 0xFF)
        elif self.ret == "s":
            h = s32((h & 0xFFFF) - 0x10000 if h & 0x8000 else h & 0xFFFF)
        elif self.ret == "S":
            h = mix(h, 0) ^ h  # x ^ y of { h, mix(h, 0) }
        elif self.ret == "d":
            h = s32(h & 0xFFFF)  # (long)(double)(h & 0xffff)
        return h & M32


def gen_groups():
    groups = {}
    # SAS/C names a __regargs function without arguments @name too
    groups["noargs"] = [Fn("")]
    core = []
    for n in range(1, 7):
        for args in itertools.product("lp", repeat=n):
            core.append(Fn("".join(args)))
    groups["core"] = core
    groups["narrow"] = ([Fn(a) for a in ("c", "s", "cc", "ss", "cs", "sc",
                                         "lc", "cl", "pc", "cp", "ccc",
                                         "sss", "clsp", "pcsl", "ccccc")]
                        + [Fn("l", "c"), Fn("l", "s"), Fn("ll", "c"),
                           Fn("p", "p"), Fn("pp", "p")])
    groups["struct"] = ([Fn(a) for a in ("S", "lS", "Sl", "pS", "Sp", "SS",
                                         "T", "lT", "Tp", "TT", "llT")]
                        + [Fn("l", "S"), Fn("lp", "S"), Fn("pl", "S")])
    asm_sets = [["d2"], ["a2"], ["d1", "d0"], ["a1", "a0"],
                ["d0", "a0", "d1", "a1"], ["d2", "d3", "d4", "d5", "d6", "d7"],
                ["a2", "d3"], ["d0", "d1", "d2", "d3", "a0", "a1", "a2", "a3"]]
    groups["asm"] = [Fn("".join("p" if r[0] == "a" else "l" for r in regs),
                        regs=regs) for regs in asm_sets]
    groups["fpu"] = ([Fn(a) for a in ("d", "dd", "ddd", "ld", "dl", "pd",
                                      "dp", "dld", "lpd", "dddd")]
                     + [Fn("l", "d"), Fn("dl", "d")])
    return groups


HEADER = """\
/* Generated by gen.py: do not edit.  */
#include "sas-abi.h"
"""


def proto(fn):
    params = []
    for k, t in enumerate(fn.args):
        if fn.regs:
            params.append("R(%s, %s, a%d)" % (fn.regs[k], TYPES[t][0], k))
        else:
            params.append("%s a%d" % (TYPES[t][0], k))
    ret = {"l": "long", "c": "signed char", "s": "short", "p": "long *",
           "S": "struct s8", "d": "double"}[fn.ret]
    asm = "ASMFN " if fn.regs else ""
    return "%s%s %s(%s)" % (asm, ret, fn.name, ", ".join(params) or "void")


def body(fn, index):
    lines = ["\tunsigned long h = 0x%08xUL;" % (SEED + index)]
    for k, t in enumerate(fn.args):
        lines.append("\th = MIX(h, %s);" % TYPES[t][1].format(a="a%d" % k))
    if fn.ret == "p":
        # Return the first pointer argument's target, moved by h's value:
        # the caller reads it back through the pointer it got.
        first = fn.args.index("p")
        lines.append("\t*a%d = (long)h;" % first)
        lines.append("\treturn a%d;" % first)
    elif fn.ret == "S":
        lines.append("\t{ struct s8 r; r.x = (long)h; r.y = (long)MIX(h, 0);"
                     " return r; }")
    elif fn.ret == "d":
        lines.append("\treturn (double)(h & 0xffff);")
    else:
        lines.append("\treturn (%s)h;" % {"l": "long", "c": "signed char",
                                           "s": "short"}[fn.ret])
    return "\n".join(lines)


def write_group(name, fns):
    with open("%s-callee.c" % name, "w") as f:
        f.write(HEADER + "\n")
        for i, fn in enumerate(fns):
            f.write("%s\n{\n%s\n}\n\n" % (proto(fn), body(fn, i)))

    with open("%s-caller.c" % name, "w") as f:
        f.write(HEADER + "\n")
        for fn in fns:
            f.write("%s;\n" % proto(fn))
        f.write("\nSTDARGS void run_%s(unsigned long *out)\n{\n" % name)
        # C89 for SAS/C: the locals the pointer and structure arguments
        # point to are declared first, the calls follow.
        decls, calls = [], []
        for i, fn in enumerate(fns):
            vals = []
            for k, t in enumerate(fn.args):
                v = arg_value(t, k)
                if t == "p":
                    decls.append("\tlong t%d_%d = %s;\n" % (i, k, c_literal("l", v)))
                    vals.append("&t%d_%d" % (i, k))
                elif t in "ST":
                    # Fields one by one: SAS/C copies an initializer from
                    # its data section, through a relocation our ld reads
                    # differently (see README).
                    decls.append("\tstruct %s t%d_%d;\n"
                                 % ("s8" if t == "S" else "s4", i, k))
                    if t == "S":
                        calls.append("\tt%d_%d.x = %dL; t%d_%d.y = %dL;\n"
                                     % (i, k, s32(v[0]), i, k, s32(v[1])))
                    else:
                        calls.append("\tt%d_%d.x = %dL;\n" % (i, k, s32(v)))
                    vals.append("t%d_%d" % (i, k))
                else:
                    vals.append(c_literal(t, v))
            call = "%s(%s)" % (fn.name, ", ".join(vals))
            if fn.ret == "p":
                calls.append("\tout[%d] = (unsigned long)*%s;\n" % (i, call))
            elif fn.ret == "S":
                calls.append("\t{ struct s8 r = %s; out[%d] = (unsigned long)"
                        "(r.x ^ r.y); }\n" % (call, i))
            elif fn.ret == "d":
                calls.append("\tout[%d] = (unsigned long)(long)%s;\n" % (i, call))
            else:
                calls.append("\tout[%d] = (unsigned long)(long)%s;\n" % (i, call))
        f.write("".join(decls) + "".join(calls) + "}\n")

    with open("%s-driver.c" % name, "w") as f:
        f.write(HEADER + "#include <stdio.h>\n\n"
                "STDARGS void run_%s(unsigned long *out);\n\n" % name)
        f.write("static const char *const names[] = {\n")
        for fn in fns:
            f.write('\t"%s",\n' % fn.name)
        f.write("};\n\nstatic const unsigned long expected[] = {\n")
        for i, fn in enumerate(fns):
            f.write("\t0x%08xUL,\n" % fn.expected(i))
        f.write("};\n\n")
        f.write("""\
int main(void)
{
	static unsigned long out[%d];
	int i, failures = 0;

	run_%s(out);
	for (i = 0; i < %d; i++)
		if (out[i] != expected[i]) {
			printf("FAIL %%s: got 0x%%08lx, want 0x%%08lx\\n",
			       names[i], out[i], expected[i]);
			failures++;
		}
	printf("%s: %%d of %d failed\\n", failures);
	return failures != 0;
}
""" % (len(fns), name, len(fns), name, len(fns)))


def main():
    for name, fns in gen_groups().items():
        write_group(name, fns)


if __name__ == "__main__":
    main()
